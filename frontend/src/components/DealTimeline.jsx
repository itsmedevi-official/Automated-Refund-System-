import { formatDateTime } from "../services/format";

export default function DealTimeline({ deal }) {
  const steps = [
    { label: "Deal created and funded", at: deal.createdAt, done: true },
    { label: "OTP generated by the delivery agent", at: deal.otpGeneratedAt, done: deal.otpGeneratedAt > 0 },
    { label: "Delivery verified on-chain", at: deal.deliveredAt, done: deal.deliveredAt > 0 },
    { label: "Dispute raised", at: deal.disputedAt, done: deal.disputedAt > 0 },
    { label: "Settled", at: deal.resolvedAt, done: deal.resolvedAt > 0 },
  ];

  return (
    <ol className="timeline">
      {steps.map((step) => (
        <li key={step.label} className={step.done ? "done" : "pending"}>
          <span className="timeline-dot" aria-hidden="true" />
          <div>
            <strong>{step.label}</strong>
            <span className="muted small">
              {step.done ? formatDateTime(step.at) : "pending"}
            </span>
          </div>
        </li>
      ))}
    </ol>
  );
}
